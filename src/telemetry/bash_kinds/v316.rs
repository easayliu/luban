/// `Be` 里一个工具的配置；没列的字段就是原文里没有那个键。
pub(super) struct TestRunner {
    /// 开关 → 它说明了什么（按 `Dt` 的顺序排，取第一个含它的）。
    pub(super) flags: Pairs,
    /// 动作词 → 它说明了什么（同上）。
    pub(super) verbs: Pairs,
    pub(super) operands: Operands,
    pub(super) bare_operands: BareOperands,
    pub(super) whole_operands: &'static [&'static str],
    pub(super) whole_needs_operand: bool,
    pub(super) less_than_package: Option<LessThanPackage>,
    pub(super) verbs_only_after: Option<&'static str>,
}

/// `operands`：操作数怎么读。
#[derive(Clone, Copy, PartialEq, Eq)]
pub(super) enum Operands {
    None,
    NameTests,
    NameTestsAfterDashes,
    GoToRecipe,
}

/// `bareOperands`：不带扩展名的操作数什么时候算目录。
#[derive(Clone, Copy, PartialEq, Eq)]
pub(super) enum BareOperands {
    None,
    Folders,
    FoldersByForm,
}

/// `lessThanPackage` 的两种正则（原文 `/\.go$/` 与 bazel 那条带前瞻的，见 [`super::less_than_package`]）。
#[derive(Clone, Copy, PartialEq, Eq)]
pub(super) enum LessThanPackage {
    GoFile,
    BazelTarget,
}

